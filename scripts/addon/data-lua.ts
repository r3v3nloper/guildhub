import { allTranslations } from "../../src/i18n/localize";
import { spellIdOfRecipeKey } from "../../src/lib/packs/recipe-key";
import type {
  LocalizedString,
  Pack,
  PackRecipe,
} from "../../src/lib/packs/schema";

// Pack data the addon needs, written into its Data.lua (SPEC 7.3):
// - Professions: the game names them only in the client's language, while the export
//   sends the skill line ID (game_ref), so the addon maps one to the other.
// - Recipes: which item a recipe makes, which items teach it and which reagents it
//   needs, so the tooltip finds crafters by item ID. The guild snapshot then only has to
//   carry spell IDs.

const luaString = (text: string) => JSON.stringify(text);

function namesByLanguage(name: LocalizedString): string {
  const entries = typeof name === "string" ? { en: name } : name;
  return Object.entries(entries)
    .map(([language, text]) => `${language} = ${luaString(text)}`)
    .join(", ");
}

function recipeLine(recipe: PackRecipe, spellId: number): string {
  const made = recipe.creates ?? "false";
  const recipeItems = recipe.recipe_items.join(", ");
  const reagents = recipe.reagents
    .filter((reagent) => reagent.item !== undefined)
    .flatMap((reagent) => [reagent.item, reagent.count])
    .join(", ");
  return `    [${spellId}] = { ${made}, { ${recipeItems} }, { ${reagents} } },`;
}

function recipeLines(pack: Pack, refs: ReadonlyMap<string, string>): string[] {
  return [...refs].flatMap(([professionId, ref]) => {
    const lines = pack.recipes
      .filter((recipe) => recipe.profession === professionId)
      .flatMap((recipe) => {
        const spellId = spellIdOfRecipeKey(recipe.id, recipe.profession);
        return spellId === undefined ? [] : [recipeLine(recipe, spellId)];
      });
    return lines.length === 0 ? [] : [`  [${ref}] = {`, ...lines, "  },"];
  });
}

export function addonDataLua(pack: Pack): string {
  const professions = pack.professions.filter(
    (profession) => profession.game_ref !== undefined,
  );
  const refs = new Map(
    professions.map((profession) => [profession.id, profession.game_ref!]),
  );
  return [
    "-- Generated by `npm run addon:data` from the GuildHub pack; do not edit by hand.",
    "local _, ns = ...",
    "",
    `ns.gameId = ${luaString(pack.id)}`,
    "",
    "-- Profession name in any client language → skill line ID (game_ref in the pack).",
    "ns.professionIds = {",
    ...professions.flatMap((profession) =>
      allTranslations(profession.name).map(
        (name) => `  [${luaString(name)}] = ${profession.game_ref},`,
      ),
    ),
    "}",
    "",
    "-- Skill line ID → name per language, for the addon's window.",
    "ns.professionNames = {",
    ...professions.map(
      (profession) =>
        `  [${profession.game_ref}] = { ${namesByLanguage(profession.name)} },`,
    ),
    "}",
    "",
    "-- Skill line ID → spell ID → { made item or false, { recipe items }, { reagent item,",
    "-- count, … } }.",
    "ns.recipes = {",
    ...recipeLines(pack, refs),
    "}",
    "",
  ].join("\n");
}
