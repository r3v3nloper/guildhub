// Builds src/app/guildhub-theme.css from PrimeReact's Lara Dark Purple theme, recoloured to the
// GuildHub palette (see the tokens in globals.css). Run after a PrimeReact update:
//   npm run theme
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const source =
  require.resolve("primereact/resources/themes/lara-dark-purple/theme.css");
const target = new URL("../src/app/guildhub-theme.css", import.meta.url);

/** Lara colour → GuildHub colour. Lower-case keys, matched case-insensitively. */
const colours = [
  ["#111827", "#0d0b17"], // ground
  ["#1c2127", "#110e1e"], // deep surfaces
  ["#1f2937", "#161325"], // cards, overlays, inputs
  ["#374151", "#241f3a"], // raised / hover surfaces
  ["#424b57", "#2c2645"], // borders
  ["#a78bfa", "#b69cff"], // primary
  ["#030712", "#140f24"], // text on primary
  ["rgba(167, 139, 250,", "rgba(182, 156, 255,"], // primary tints
  ["rgba(255, 255, 255, 0.87)", "#eeeaf8"], // text
  ["rgba(255, 255, 255, 0.6)", "#a49dbd"], // secondary text
];

const escape = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

let css = readFileSync(source, "utf8");
// The app ships its own fonts; Lara's Inter files would not resolve from here anyway.
css = css.replace(/@font-face\s*{[^}]*}/g, "");
css = css.replaceAll(
  '"Inter var", sans-serif',
  '"Plus Jakarta Sans Variable", system-ui, sans-serif',
);
css = css.replaceAll('"cv02", "cv03", "cv04", "cv11"', "normal");
for (const [from, to] of colours) {
  css = css.replace(new RegExp(escape(from), "gi"), to);
}

writeFileSync(
  target,
  `/* Generated by scripts/build-theme.mjs from PrimeReact Lara Dark Purple. Do not edit. */\n${css}`,
);
console.log(`Theme geschrieben: ${target.pathname}`);
